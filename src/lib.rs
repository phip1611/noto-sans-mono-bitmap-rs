/// A pre-rasterized character (glyph) of the font.
///
/// # Pixel Layout
///
/// The glyph is a box of [`Self::width`] x [`Self::height`] pixels. Each pixel
/// is one byte that describes its intensity (coverage) from `0` (background)
/// to `255` (foreground). The pixels are stored flat in row-major order, i.e.,
/// row by row from top to bottom, and each row from left to right. Hence, the
/// pixel at `(x, y)` is `pixels()[y * width() + x]`.
///
/// Use [`Self::rows`] to iterate the rows, [`Self::pixels`] to access the raw
/// bytes, or [`Self::pixel`] to access a single pixel.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct RasterizedChar {
    /// The pixels in row-major order; exactly `width * height` bytes.
    pixels: &'static [u8],
    /// Height of the raster box. The actual font size is slightly smaller.
    height: usize,
    /// The width of the rasterized char. It is guaranteed, that all chars
    /// of the same font weight and raster height also have the same width
    /// (as you would expect from a mono font.)
    width: usize,
}

impl RasterizedChar {
    /// Returns all pixels of the glyph as flat slice in row-major order (top
    /// row first, each row from left to right).
    ///
    /// The slice is exactly [`Self::width`] * [`Self::height`] bytes long. Each
    /// byte describes the intensity of a pixel from 0 to 255. The pixel at
    /// `(x, y)` is at index `y * width() + x`.
    #[inline]
    pub const fn pixels(&self) -> &'static [u8] {
        self.pixels
    }

    /// Returns an iterator over the rows of the glyph, from top to bottom.
    ///
    /// Yields exactly [`Self::height`] rows, each being a slice of exactly
    /// [`Self::width`] bytes (pixels from left to right).
    #[inline]
    pub fn rows(&self) -> core::slice::ChunksExact<'static, u8> {
        self.pixels.chunks_exact(self.width)
    }

    /// Returns the intensity of the pixel at column `x` and row `y` (origin is
    /// the top left corner), or `None` if the coordinates are out of bounds.
    #[inline]
    pub const fn pixel(&self, x: usize, y: usize) -> Option<u8> {
        if x < self.width && y < self.height {
            Some(self.pixels[y * self.width + x])
        } else {
            None
        }
    }

    /// Height of the raster box. The actual font size is slightly smaller.
    #[inline]
    pub const fn height(&self) -> usize {
        self.height
    }

    /// The width of the raster char. It is guaranteed, that all chars
    /// of the same font weight and raster height also have the same width
    /// (as you would expect from a mono font).
    #[inline]
    pub const fn width(&self) -> usize {
        self.width
    }
}

